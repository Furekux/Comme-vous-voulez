def random_pokemon():
    return pokemons[randint(0,len(pokemons))]

def garder_pokemon(p):
    pokedex.append(p)

def supp_pokemon(p):
    if type(p)==str:
        for i in range(len(pokedex)) :
            if pokedex[i]==p:
                pokedex.pop(i)
                return None
    elif type(p)==int:
        if p<len(pokedex) and p>=0:
            pokedex.pop(p)

